/**
 * 后端业务错误码 → 中文提示映射。
 *
 * 与 docs/API/phase-1-contracts.md §2 严格对齐。前端在捕获 ApiError
 * 后应优先用此表兜底展示，避免直接把 message 透传（后端 message 有时
 * 为英文调试信息）。
 *
 * 特别注意：
 * - 1003 密码错误 / 1004 账号被禁用 → 登录页专用错误提示
 * - 3003 申请不存在 / 3004 申请状态不允许 → 审核台专用
 * - 1020 权限不足 → 全局兜底（RequirePermission 也会用）
 */

export const ERROR_MESSAGES: Record<number, string> = {
  // 1xxx 认证 & 会话
  1001: "请先登录",
  1002: "登录已过期，请重新登录",
  1003: "账号或密码错误",
  1004: "账号已被禁用，请联系超级管理员",
  1005: "登录状态失效，请重新登录",
  1010: "验证码错误或已过期",
  1020: "无权限执行此操作",

  // 2xxx 用户资料
  2001: "用户不存在",
  2010: "旧密码错误",

  // 3xxx 商家 & 入驻
  3001: "该用户已提交过入驻申请且未处理完",
  3002: "该用户已是商家",
  3003: "申请不存在或已被删除",
  3004: "申请当前状态不允许该操作",
  3010: "商家账号已被冻结",

  // 4xxx Admin 域
  4001: "管理员账号不存在",
  4020: "管理员权限不足",

  // 5xxx 通用校验
  5001: "请求参数校验失败",
  5002: "资源不存在",
  5003: "请求过于频繁，请稍后再试",

  // 9xxx 服务端
  9000: "服务器开小差了，请稍后重试",
};

/**
 * 根据错误码返回中文提示。若未映射则返回 fallback。
 */
export function getErrorMessage(code: number, fallback = "操作失败"): string {
  return ERROR_MESSAGES[code] ?? fallback;
}
